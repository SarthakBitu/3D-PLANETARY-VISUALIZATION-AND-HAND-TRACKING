export function searchCosmicEntities(query: string): CelestialBodyInfo[] {
  const q = query.trim().toLowerCase();
  const all = [...SOLAR_BODIES, ...GALAXY_REGIONS];
  if (!q) return all;
  return all.filter(
    (b) =>
      b.name.toLowerCase().includes(q) ||
      b.category.toLowerCase().includes(q) ||
      (q.includes('milky') && b.scale === 'galaxy') ||
      (q.includes('galaxy') && b.scale === 'galaxy') ||
      (q.includes('solar') && b.scale === 'solar')
  );
}
